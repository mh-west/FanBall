"""Builds dist/rotations.js: five starters per team (user's list, 2026-11-12), for picking the starter in AI
matches and admin-booked games.

Sources, in order: the hand-checked starter data already in dist/app.js (STARTING_PITCHERS: rates, pitch mix
and speeds) for those ten; otherwise the Namu Wiki 2026 line found by tools/namu-pitcher-stats.py /
tools/find-pitcher-season.py (2025 when the page has no 2026 yet). Rates per batter faced with
TBF ~= 3 x IP + H + BB + HBP. Pitch mixes for the others are typical by arm slot (estimated, display only).
A pitcher with no usable record gets league-average starter rates (marked).

Usage: python3 -I tools/build-rotations.py <pitchers.json> <found.jsonl> [more.jsonl ...]
"""
import json, sys

ROTATIONS = {
    'lg': ['톨허스트', '임찬규', '웰스', '송승기', '카라스코'], 'kt': ['고영표', '소형준', '대니엘', '로건', '오원석'],
    'ssg': ['김건우', '다케다', '최민준', '김민준', '아빌라'], 'nc': ['구창모', '토다', '테일러', '라일리', '신민혁'],
    'doosan': ['곽빈', '잭로그', '최민석', '벤자민', '최승용'], 'tigers': ['네일', '올러', '시라카와', '양현종', '황동하'],
    'lotte': ['로드리게스', '박세웅', '나균안', '비슬리', '김진욱'], 'samsung': ['원태인', '후라도', '페덱', '최원태', '장찬희'],
    'hanwha': ['왕옌청', '류현진', '화이트', '에르난데스', '황준서'], 'kiwoom': ['하영민', '알칸타라', '안우진', '박준현', '배동현'],
}
MIX = {
    'over': {'포심': [[143, 151], 46], '슬라이더': [[130, 137], 22], '체인지업': [[128, 134], 14], '커브': [[115, 123], 10], '포크': [[130, 136], 8]},
    'side': {'투심': [[136, 144], 44], '슬라이더': [[123, 130], 30], '체인지업': [[121, 128], 26]},
    'under': {'투심': [[128, 136], 46], '커브': [[108, 116], 24], '체인지업': [[115, 122], 30]},
}
LEAGUE = (0.262, 0.088, 0.190)

src = json.load(open(sys.argv[1], encoding='utf8'))
import os
manual = json.load(open('data/pitchers-manual-2026.json', encoding='utf8'))['pitchers'] if os.path.exists('data/pitchers-manual-2026.json') else {}
found = {}
for path in sys.argv[2:]:
    for line in open(path, encoding='utf8'):
        try:
            r = json.loads(line)
        except ValueError:
            continue
        if r.get('found'):
            found[f"{r['team']}:{r['name']}"] = r

# The ten starters already in dist/app.js keep their checked data (read from the page script).
app = open('dist/app.js', encoding='utf8').read()
start = app.index('const STARTING_PITCHERS=')
block = app[start:app.index('};', start) + 2]


def rates(p):
    ip, h, bb, hbp, k = (p.get(x) or 0 for x in ('ip', 'h', 'bb', 'hbp', 'k'))
    tbf = 3 * ip + h + bb + hbp
    if tbf < 60 or not k:
        return None
    return round(h / max(1.0, tbf - bb - hbp), 3), round((bb + hbp) / tbf, 3), round(k / tbf, 3)


out, report = {}, []
for team, names in ROTATIONS.items():
    rows = []
    for name in names:
        if f"name:'{name}'" in block and team in block.split(f"name:'{name}'")[0].rsplit('\n', 1)[-1]:
            rows.append({'name': name, 'fromApp': True})
            report.append(f'{team} {name}: dist/app.js 선발 데이터')
            continue
        p = found.get(f'{team}:{name}') or src.get(f'{team}:{name}') or {}
        m = manual.get(f'{team}:{name}')
        if m:  # the user's 2026 line and pitch mix win
            p = {**p, **{k: m[k] for k in ('games', 'ip', 'h', 'hr', 'bb', 'hbp', 'k')}, 'how': 'yearly_table', 'season': 2026, 'source': m['source'], 'found': True}
        if p.get('how') not in (None, 'yearly_table', 'yearly_2025') and not p.get('found'):
            p = {}
        # 2026 only (user decision 2026-11-12): a 2025 line is not used.
        if p.get('how') == 'yearly_2025' or p.get('season') == 2025:
            p = {k: p.get(k) for k in ('throws', 'slot', 'source')}
        r = rates(p) if p.get('ip') else None
        slot = p.get('slot') or 'over'
        mix = {t: [m['speeds'][t], m['mix'][t]] for t in m['mix']} if m else MIX.get(slot, MIX['over'])
        season = p.get('season') or (2025 if p.get('how') == 'yearly_2025' else 2026)
        rows.append({'name': name, 'throws': p.get('throws') or 'R', 'slot': slot,
                     'avg': (r or LEAGUE)[0], 'bb': (r or LEAGUE)[1], 'k': (r or LEAGUE)[2],
                     'games': p.get('games'), 'ip': p.get('ip'), 'season': season if r else None,
                     'note': None if r else '기록 없음: 리그 평균 선발 값',
                     'speeds': {t: v[0] for t, v in mix.items()}, 'mix': {t: v[1] for t, v in mix.items()}, 'mix_note': '추정(팔 각도별 대표 구성)',
                     'source': p.get('source')})
        report.append(f"{team} {name}: {'%s %sG %sIP' % (season, p.get('games'), round(p.get('ip') or 0, 1)) if r else '기록 없음(리그 평균)'} {p.get('throws') or '?'} {slot}")
    out[team] = rows

head = ('/* Generated by tools/build-rotations.py: five starters per team (user list 2026-11-12). Records from Namu Wiki\n'
        '   (CC BY-NC-SA 2.0 KR, source URL per pitcher); entries with fromApp use STARTING_PITCHERS in dist/app.js. */\n')
open('dist/rotations.js', 'w', encoding='utf8').write(head + 'window.FANBALL_ROTATIONS=' + json.dumps(out, ensure_ascii=False) + ';\n')
print('\n'.join(report))
