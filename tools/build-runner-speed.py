"""Runner speed grades and steal tendency from career lines (user decision 2026-11-12).

The user's rule: how often a player runs shows in his career steals against the times he reached first
(singles + walks); a pinch runner such as 김민규 has many steals for few plate appearances, which this catches.
- steal rate = SB / (1B + BB), shrunk toward the league (0.05) with 40 times on first, so short careers stay near 3.
- speed grade 1..5 from that rate; +1 (up to 5) when triples are a large share of extra-base hits
  (3B / (2B + 3B) >= 0.15 with 8+ triples), a sign of speed beyond steals.
- steal tendency: 많음 / 보통 / 적음 from the same rate.
- No career table (rookies, players without a Namu by-year table): grade 3, 보통 (marked).
- data/runner-speed-overrides.json ({"team:name": {"speed": 5, "steal": "적음", "why": "..."}}) wins.

Outputs data/runner-speed.json (draft with the numbers behind each grade) and dist/runner-speed.js.
Usage: python3 -I tools/build-runner-speed.py <career-batting.json>
"""
import json, os, sys

career = json.load(open(sys.argv[1], encoding='utf8'))
over_path = 'data/runner-speed-overrides.json'
overrides = json.load(open(over_path, encoding='utf8')) if os.path.exists(over_path) else {}
PRIOR, K = 0.05, 40
GRADE = [(0.20, 5), (0.12, 4), (0.06, 3), (0.025, 2), (0, 1)]
STEAL = [(0.15, '많음'), (0.06, '보통'), (0, '적음')]

out, js = {}, {}
for key, v in career.items():
    team, name = key.split(':', 1)
    c = (v or {}).get('career') or {}
    h, d2, d3, hr, bb, sb = (c.get(x, 0) for x in ('H', '2B', '3B', 'HR', 'BB', 'SB'))
    singles = h - d2 - d3 - hr
    row = {'team': team, 'name': name, 'source': (v or {}).get('url')}
    if not c or singles < 0 or 'SB' not in c:
        row.update({'speed': 3, 'steal': '보통', 'basis': '통산 기록표 없음: 기본값'})
    else:
        on_first = singles + bb
        rate = (sb + PRIOR * K) / (on_first + K)
        grade = next(g for t, g in GRADE if rate >= t)
        triple_share = d3 / (d2 + d3) if d2 + d3 else 0
        bump = d3 >= 8 and triple_share >= 0.15
        if bump:
            grade = min(5, grade + 1)
        steal = next(s for t, s in STEAL if rate >= t)
        row.update({'speed': grade, 'steal': steal, 'g': int(c.get('G', 0)), 'sb': int(sb), 'on_first': int(on_first),
                    'raw_rate': round(sb / on_first, 3) if on_first else None, 'rate': round(rate, 3), 'triples': int(d3),
                    'basis': f"통산 도루 {int(sb)} / (단타+볼넷) {int(on_first)}" + (f", 3루타 {int(d3)}개(장타 중 {triple_share:.0%})로 +1" if bump else '')})
    o = overrides.get(key)
    if o:
        row.update({k: o[k] for k in ('speed', 'steal') if k in o}); row['override'] = o.get('why') or '사용자 지정'
    out[key] = row
    js.setdefault(team, {})[name] = [row['speed'], {'적음': 1, '보통': 2, '많음': 3}[row['steal']]]

json.dump({'rule': __doc__.split('Outputs')[0].strip(), 'players': out}, open('data/runner-speed.json', 'w', encoding='utf8'), ensure_ascii=False, indent=1)
head = ('/* Generated by tools/build-runner-speed.py: runner speed grade 1-5 and steal tendency (1 적음, 2 보통, 3 많음)\n'
        '   per player, from career steals per time on first (Namu Wiki by-year tables, CC BY-NC-SA 2.0 KR). */\n')
open('dist/runner-speed.js', 'w', encoding='utf8').write(head + 'window.FANBALL_RUNNER_SPEED=' + json.dumps(js, ensure_ascii=False) + ';\n')
from collections import Counter
print(Counter(r['speed'] for r in out.values()), Counter(r['steal'] for r in out.values()))
